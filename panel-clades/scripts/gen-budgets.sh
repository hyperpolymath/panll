# gen-budgets.sh [--check] — generate src/abi/PanelClades/ABI/Budgets.idr
# from the `resources` block of every clades/*/config.k9.ncl that has one.
#
# The clade config is the single source of a clade's declared resource
# budgets; Grades.idr builds each contract from the generated values, so a
# budget its declared grades do not fit fails the typecheck.
#
# The block must be written one record per line, exactly:
#
#   resources = {
#     status = "DESIGNED",
#     state = { peak = <n>, drift = <n>, budget = <n> },
#     crossing = { loss = <n>, tolerance = <n> },
#   },
#
# A block that is present but not in this shape is an error, never a skip.
# (No Nickel evaluator runs here: the estate CI has none, and a sed
# transcription of a fixed shape is checkable.  The shape is the contract.)
#
# --check: regenerate into a temporary file and fail if it differs from the
# committed one (the staleness gate check-abi.sh runs).
set -euo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.."
OUT="src/abi/PanelClades/ABI/Budgets.idr"
mode="${1:-write}"
fail() { printf 'gen-budgets: %s\n' "$1" >&2; exit 1; }

# kebab-case clade id -> lowerCamelCase Idris name
camel() { printf '%s' "$1" | sed -E 's/-([a-z0-9])/\U\1/g'; }

nat='[0-9]+'
emit() {
  cat <<'HEADER'
-- SPDX-License-Identifier: MPL-2.0
-- Copyright (c) 2026 Jonathan D.A. Jewell (hyperpolymath) <j.d.a.jewell@open.ac.uk>
--
-- GENERATED by panel-clades/scripts/gen-budgets.sh from the `resources`
-- block of each clades/*/config.k9.ncl.  Do not edit: change the config and
-- re-run the script (check-abi.sh fails when this file is stale).
--
||| Declared resource budgets of the panel clades that declare them.
||| DESIGNED values (the configs say so), not measurements.
module PanelClades.ABI.Budgets

%default total

||| A clade's declared resources, as written in its config.
public export
record DeclaredResources where
  constructor MkDeclaredResources
  ||| Peak live panel state over one inference (occupancy).
  peak      : Nat
  ||| State still held at the end of one inference.
  drift     : Nat
  ||| The budget the peak must fit.
  budget    : Nat
  ||| Loss on the Panel-N → Panel-W crossing.
  loss      : Nat
  ||| The crossing's loss tolerance.
  tolerance : Nat
HEADER
  local n=0 cfg dir id state crossing
  for cfg in clades/*/config.k9.ncl; do
    grep -qE '^[[:space:]]*resources[[:space:]]*=' "$cfg" || continue
    dir="$(basename -- "$(dirname -- "$cfg")")"
    id="$(camel "$dir")"
    block="$(sed -n '/^[[:space:]]*resources[[:space:]]*=/,/^[[:space:]]*},[[:space:]]*$/p' "$cfg")"
    state="$(printf '%s\n' "$block" | grep -E "^[[:space:]]*state = \{ peak = $nat, drift = $nat, budget = $nat \},[[:space:]]*$" || true)"
    crossing="$(printf '%s\n' "$block" | grep -E "^[[:space:]]*crossing = \{ loss = $nat, tolerance = $nat \},[[:space:]]*$" || true)"
    [ "$(printf '%s\n' "$state" | grep -c .)" -eq 1 ] \
      || fail "$cfg: resources.state is not one line of the form { peak = n, drift = n, budget = n }"
    [ "$(printf '%s\n' "$crossing" | grep -c .)" -eq 1 ] \
      || fail "$cfg: resources.crossing is not one line of the form { loss = n, tolerance = n }"
    printf '%s\n' "$block" | grep -qE '^[[:space:]]*status = "DESIGNED",' \
      || fail "$cfg: resources.status must be \"DESIGNED\" (nothing measures these values yet)"
    read -r peak drift budget < <(printf '%s\n' "$state" | sed -E 's/.*peak = ([0-9]+), drift = ([0-9]+), budget = ([0-9]+).*/\1 \2 \3/')
    read -r loss tolerance < <(printf '%s\n' "$crossing" | sed -E 's/.*loss = ([0-9]+), tolerance = ([0-9]+).*/\1 \2/')
    cat <<EOF

||| Declared in clades/$dir/config.k9.ncl.
public export
$id : DeclaredResources
$id = MkDeclaredResources $peak $drift $budget $loss $tolerance
EOF
    n=$((n + 1))
  done
  [ "$n" -gt 0 ] || fail "no clades/*/config.k9.ncl declares a resources block"
}

case "$mode" in
  write)
    emit > "$OUT.tmp"; mv "$OUT.tmp" "$OUT"
    echo "gen-budgets: wrote $OUT" ;;
  --check)
    tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT
    emit > "$tmp"
    if ! diff -u "$OUT" "$tmp"; then
      fail "$OUT is stale: run panel-clades/scripts/gen-budgets.sh"
    fi
    echo "gen-budgets: $OUT is current" ;;
  *) fail "usage: gen-budgets.sh [--check]" ;;
esac
